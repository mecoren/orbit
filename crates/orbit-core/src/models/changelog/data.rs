//! 应用内更新日志数据（**发版时只改这一处**：在 `vec!` 头部追加一条）
//!
//! 与仓库根 `CHANGELOG.md` 分工见 [super] 模块注释；本文件是双端「关于 → 更新日志」
//! 的唯一数据源，桌面 Tauri 与移动 FRB 都经 `api::changelog_api::changelog_versions` 读取。
//!
//! 0.1.0 是唯一已发布版本：条目按当前代码全量归并（含发版后各批次，逐批明细见
//! `CHANGELOG.md` 的 [Unreleased] 段）；`date` 仍是发版日期。桌面与移动渲染同一份，
//! 端特有形态在条目内分别标注，不写成「两端全功能」。
//!
//! 条目一律用 `v("x.y.z", "YYYY-MM-DD", "summary", vec![e(...)])` 形式追加：
//! `release-consistency.test.ts` 用最小正则解析首条 `vec![v(...)`，手写成结构体字面量会让护栏失明。
use std::sync::LazyLock;

use super::{ChangelogCategory as C, ChangelogEntry, ChangelogVersion};

fn e(category: C, description: &str) -> ChangelogEntry {
    ChangelogEntry {
        category,
        description: description.to_string(),
    }
}

fn v(version: &str, date: &str, summary: &str, changes: Vec<ChangelogEntry>) -> ChangelogVersion {
    ChangelogVersion {
        version: version.to_string(),
        date: date.to_string(),
        summary: summary.to_string(),
        changes,
    }
}

