/** 供 almanac.ts 等模块复用同一份压缩表（勿修改字面量） */
export { LUNAR_INFO };

/** 农历基准日：1900-01-31（正月初一） */
const LUNAR_BASE = Date.UTC(1900, 0, 31);

function info(y: number): number {
  return LUNAR_INFO[y - 1900];
}

/** 某农历年的闰月月份（0 = 无闰月） */
function leapMonth(y: number): number {
  return info(y) & 0xf;
}

/** 某农历年闰月的天数（无闰月为 0） */
function leapDays(y: number): number {
  if (leapMonth(y) === 0) return 0;
  return (info(y) & 0x10000) !== 0 ? 30 : 29;
}

/** 某农历年平月 m 的天数 */
function monthDays(y: number, m: number): number {
  return (info(y) & (0x10000 >> m)) !== 0 ? 30 : 29;
}

/** 某农历年总天数（含闰月） */
function yearDays(y: number): number {
  let sum = 348;
  for (let mask = 0x8000; mask > 0x8; mask >>= 1) {
    if ((info(y) & mask) !== 0) sum += 1;
  }
  return sum + leapDays(y);
}

/**
 * 农历（year, month, day，平月语义）→ 公历 Date（UTC 零点）。
 * 无效日期（越界/该年无此月/日超当月天数）返回 null。
 */
export function lunarToSolarDate(
  year: number,
  month: number,
  day: number,
): Date | null {
  if (year < 1901 || year > 2100) return null;
  if (month < 1 || month > 12 || day < 1 || day > 30) return null;
  const leap = leapMonth(year);
  if (day > monthDays(year, month)) return null;

  let offset = 0;
  for (let y = 1900; y < year; y++) {
    offset += yearDays(y);
  }
  // 月偏移：累加平月 1..month-1；若某平月恰为闰月，其后紧跟闰月一并计入
  for (let m = 1; m < month; m++) {
    offset += monthDays(year, m);
    if (leap === m) offset += leapDays(year);
  }
  offset += day - 1;
  return new Date(LUNAR_BASE + offset * 86400000);
}

/** Date → YYYY-MM-DD（按本地年月日） */
export function formatYmd(d: Date): string {
  const y = d.getFullYear();
  const m = String(d.getMonth() + 1).padStart(2, "0");
  const day = String(d.getDate()).padStart(2, "0");
  return `${y}-${m}-${day}`;
}
